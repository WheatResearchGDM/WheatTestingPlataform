const assert = require('node:assert/strict');
const load = require('./load-typescript.cjs')();
const { generateListLayout } = load('lib/listLayout.ts');
const { duplicatePlotIds, plotCellKey, plotIssueFor } = load('lib/plotIdentity.ts');
const { validateLayout } = load('lib/layoutValidation.ts');
const entries = [{ plotId: '001', trial: 'A', genotype: 'G1' }, { plotId: '001', trial: 'A', genotype: 'G2' }];
const result = generateListLayout(entries, { rows: 1, width: 1.2, length: 6, strip: 12 });
assert.equal(result.plots.length, 2); assert.equal(duplicatePlotIds(result.plots).join(','), '001');
assert.notEqual(plotCellKey(result.plots[0]), plotCellKey(result.plots[1]));
assert.equal(result.plots[1].genotype, 'G2');
validateLayout({ plots: result.plots, allocations: result.allocations, settings: { plotLength: 1.2, plotWidth: 6, gapLength: 0, gapWidth: 0, rotation: 0, center: [-28, -52] }, metadata: { city: 'Teste', plannedSowingDate: '2026-11-10' } });
const issue = { kind: 'Parcela perdida', note: 'Somente a primeira célula', updatedAt: '2026-11-03T10:00:00Z' };
const issues = { [plotCellKey(result.plots[0])]: issue };
assert.equal(plotIssueFor(issues, result.plots[0]).note, issue.note);
assert.equal(plotIssueFor(issues, result.plots[1]), undefined);
assert.equal(plotIssueFor({ '001': issue }, result.plots[1]).kind, 'Parcela perdida', 'legacy PlotID-wide records still load');
assert.equal(plotIssueFor({ '001': issue, [plotCellKey(result.plots[0])]: { ...issue, cleared: true, updatedAt: '2026-11-04' } }, result.plots[0]), undefined);
const { diseaseRecordDetails } = load('lib/diseaseRecord.ts');
const disease = diseaseRecordDetails(4, ['giberela', 'mosaico', 'outros'], 'Observação de campo');
assert.equal(disease.doencas, '4'); assert.equal(disease.doenca_giberela, 'Sim'); assert.equal(disease.doenca_oidio, 'Não');
assert.equal(disease.doencas_identificadas, 'Mosaico; Giberela; Outros'); assert.equal(disease.doencas_observacoes, 'Observação de campo');
assert.equal(diseaseRecordDetails(1, ['giberela'], 'antiga').doencas_identificadas, '');
assert.throws(() => diseaseRecordDetails(3, [], ''), /Selecione/);
console.log('Requested adjustments: repeated PlotIDs remain separate, warnings do not block saving, cell-specific issues and one disease score passed.');

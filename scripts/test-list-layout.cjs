const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync(require('node:path').join(__dirname, '../lib/listLayout.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const sandbox = { exports: {} }; vm.runInNewContext(compiled, sandbox);
const { generateListLayout } = sandbox.exports;
const entry = (n, trial = 'U01') => ({ plotId: String(n), trial, genotype: `G${n}` });
const options = { rows: 2, width: 1.2, length: 6, strip: 12 };
const result = generateListLayout(Array.from({ length: 23 }, (_, i) => entry(i + 1)), options);
assert.equal(result.plots[0].col, 1);
assert.equal(result.plots[9].col, 10);
assert.equal(result.plots[10].row, 2);
assert.equal(result.plots[10].col, 10);
assert.equal(result.plots[19].col, 1);
assert.equal(result.plots[20].col, 11);
assert.equal(result.plots[20].row, 1);
assert.equal(result.width, 24); assert.equal(result.height, 12);
assert.equal(new Set(result.plots.map((p) => `${p.row}:${p.col}`)).size, 23);
const mixed = generateListLayout([entry(1), entry(3, 'K01'), entry(2)], options);
assert.equal(mixed.allocations.length, 2);
assert.equal(mixed.plots[1].plotId, '2');
assert.equal(mixed.plots[2].col, 11);
assert.throws(() => generateListLayout([entry(1), entry(1)], options), /duplicado/);
assert.throws(() => generateListLayout([entry(1)], { ...options, strip: 11 }), /pelo menos/);
assert.throws(() => generateListLayout([entry(1)], { ...options, rows: 1.5 }), /rows/);
assert.throws(() => generateListLayout([{ ...entry(1), genotype: '' }], options), /preencha/);
assert.equal(generateListLayout([{ ...entry(1), plotId: '001A' }], options).plots[0].plotId, '001A');
console.log('List layout: zigzag, overflow, dimensions, trial boundaries and validation passed.');
